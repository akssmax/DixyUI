const clone = (value) => JSON.parse(JSON.stringify(value));

test("all eleven shipped artifacts are compiled from portable documents", async () => {
  for (const manifest of manifests) {
    const result = compileThemeDocument(JSON.stringify(manifest.document));
    const shipped = await import(`../dist/skins/${manifest.slug}.js`);
    assert.deepEqual(result.definition, shipped.default);
    assert.deepEqual(result.themeProps, shipped[manifest.symbol + "Theme"]);
    assert.equal(result.css, compileThemeDocument(result.document).css);
    assert.equal(
      await format(
        "/* Generated by scripts/generate-skins.mjs. Do not edit. */\n" +
          result.css,
        { parser: "css" },
      ),
      fs.readFileSync(
        new URL(`../generated/${manifest.slug}.css`, import.meta.url),
        "utf8",
      ),
    );
    assert.equal(
      Object.hasOwn(result.themeProps, "material"),
      false,
      "A default material must not become an explicit material override",
    );
    assert.ok(Object.isFrozen(result.document.recipes.frame.parameters));
  }
});

test("document validation rejects executable, malformed and unsupported data with field diagnostics", () => {
  const invalid = [
    (d) => {
      d.schemaVersion = 99;
    },
    (d) => {
      d.revision = 0;
    },
    (d) => {
      d.id = 'escape/name"]{}';
    },
    (d) => {
      d.recipes.material.version = 2;
    },
    (d) => {
      d.recipes.frame.id = "remote/shader";
    },
    (d) => {
      d.recipes.frame.parameters.width = 99;
    },
    (d) => {
      d.recipes.material.parameters.surfaceMix = NaN;
    },
    (d) => {
      d.foundations.bodyFont = "url(unsafe)";
    },
    (d) => {
      d.recipes.frame.parameters.css = "body{display:none}";
    },
    (d) => {
      d.children = "fake controls";
    },
    (d) => {
      delete d.foundations.radius;
    },
    (d) => {
      Object.defineProperty(d, "name", {
        get() {
          throw new Error("Must not execute an accessor");
        },
      });
    },
  ];
  for (const mutate of invalid) {
    const document = clone(themeDocuments[0]);
    mutate(document);
    assert.throws(
      () => parseThemeDocument(document),
      (error) =>
        error instanceof ThemeDocumentError &&
        error.issues.length > 0 &&
        error.issues.every((issue) => issue.path.startsWith("$")),
    );
  }
  for (const value of [
    null,
    [],
    "null",
    "{bad json",
    " ".repeat(32769),
    JSON.parse('{"__proto__":{"polluted":true}}'),
  ])
    assert.throws(() => parseThemeDocument(value), ThemeDocumentError);
  assert.equal({}.polluted, undefined);
});

test("a fork changes scoped paint, geometry and settings without mutating an installed theme", () => {
  const document = clone(themeDocuments[3]);
  document.id = "acme/workbench";
  document.name = "Workbench";
  document.revision = 2;
  document.foundations.radius = "none";
  document.foundations.border = 2;
  document.foundations.headingFont = "serif";
  document.recipes.frame.parameters.width = 4;
  document.recipes.frame.parameters.paddingInline = 48;
  document.recipes.material.parameters.surfaceMix = 30;
  document.recipes.material.parameters.darkSurfaceMix = 80;
  const compiled = compileThemeDocument(document);
  assert.match(compiled.css, /data-dixy-skin="acme\/workbench"/);
  assert.doesNotMatch(compiled.css, /data-dixy-skin="dixy\//);
  assert.match(compiled.css, /border:4px/);
  assert.match(compiled.css, /30px 48px 30px/);
  assert.match(compiled.css, /surface-raised\) 30%/);
  assert.match(compiled.css, /surface-raised\) 80%/);
  assert.equal(compiled.themeProps.radius, "none");
  assert.equal(compiled.themeProps.style["--dixy-button-border-width"], "2px");
  assert.match(compiled.themeProps.style["--dixy-font-display"], /Georgia/);
  assert.equal(
    compiled.renderer.entry,
    "@dixy-ui/themes/studio-hardware/react",
  );
  document.recipes.frame.parameters.width = 8;
  assert.equal(compiled.document.recipes.frame.parameters.width, 4);
  assert.equal(themeDocuments[3].recipes.frame.parameters.width, 1);
});

test("v2 materials and frames compose independently and legacy documents migrate", () => {
  for (const material of Object.keys(materialRecipes))
    for (const frame of Object.keys(frameRecipes)) {
      const document = clone(themeDocuments[3]);
      document.id = "custom/matrix";
      document.recipes.material.id = material;
      document.recipes.frame.id = frame;
      const compiled = compileThemeDocument(document);
      assert.ok(compiled.css.includes(materialRecipes[material].finish));
      assert.equal(
        compiled.renderer?.entry ?? null,
        frameRecipes[frame].rendererEntry
          ? "@dixy-ui/themes/" + frameRecipes[frame].rendererEntry
          : null,
      );
      assert.equal(compiled.document.recipes.material.id, material);
      assert.equal(compiled.document.recipes.frame.id, frame);
    }
  const legacy = clone(themeDocuments[0]);
  legacy.schemaVersion = 1;
  for (const key of [
    "componentFinish",
    "customAccent",
    "lightness",
    "chroma",
    "hue",
  ])
    delete legacy.foundations[key];
  for (const key of [
    "sheen",
    "cushion",
    "inkTint",
    "textureScale",
    "lightAngle",
    "backdropBlur",
    "backdropSaturate",
  ])
    delete legacy.recipes.material.parameters[key];
  delete legacy.recipes.frame.parameters.cornerScale;
  delete legacy.recipes.frame.ornament;
  delete legacy.character;
  const migrated = parseThemeDocument(legacy);
  assert.equal(migrated.schemaVersion, 6);
  assert.deepEqual(migrated.character, defaultCharacter);
  assert.equal(migrated.recipes.material.parameters.textureScale, 1);
  assert.equal(migrated.recipes.frame.id, "forest");
  assert.ok(Object.isFrozen(themeDocumentSchema.properties.foundations));
  const document = clone(themeDocuments[3]);
  document.recipes.frame.parameters.cornerVariation = 0.2;
  assert.match(compileThemeDocument(document).css, /radius-card\) \* 1.2/);
});

test("shared cushion, ink and corner parameters transfer between materials and frames", () => {
  const document = clone(themeDocuments[7]);
  document.id = "custom/soft-machine";
  document.recipes.material.id = "titanium";
  document.recipes.frame.id = "deco";
  const compiled = compileThemeDocument(document);
  assert.match(compiled.css, /--dixy-skin-cushion:inset 0 2.55px/);
  assert.match(compiled.css, /--dixy-color-text-primary:color-mix/);
  assert.match(compiled.css, /radius-card\) \* 1.724/);
  assert.equal(compiled.renderer.entry, "@dixy-ui/themes/art-deco/react");
  document.foundations.depth = "none";
  assert.equal(
    compileThemeDocument(document).themeProps.style[
      "--dixy-skin-cushion-elevation"
    ],
    "0 0 0 transparent",
  );
  document.recipes.material.parameters.cushion = 1.1;
  assert.throws(() => parseThemeDocument(document), ThemeDocumentError);
});

test("No frame preserves paint and content insets without renderer or decorative stroke", () => {
  for (const source of themeDocuments) {
    const document = clone(source);
    document.recipes.frame.id = "none";
    // Even an imported stale decorative width must not restore a frame.
    document.recipes.frame.parameters.width = 8;
    // Chrome controls legitimately clip their own thumbs; this checks frame output only.
    document.character.controls = "standard";
    // Window chrome (notched corners) is character, not frame output.
    document.character.chrome = {
      ...document.character.chrome,
      corners: "inherit",
    };
    const compiled = compileThemeDocument(document);
    assert.equal(compiled.renderer, null);
    assert.match(compiled.css, /border:0px solid/);
    assert.ok(
      compiled.css.includes(
        materialRecipes[document.recipes.material.id].finish,
      ),
    );
    assert.doesNotMatch(compiled.css, /dixy-frame-corner|clip-path:polygon/);
  }
});
