type Foundations = {
  accentColor: string;
  neutralColor: string;
  radius: "none" | "sm" | "md" | "lg" | "full";
  shape: "rounded" | "pill" | "square";
  appearance: "light" | "dark";
  bodyFont: string;
  headingFont: string;
  border: 1 | 2;
  depth: "none" | "raised" | "floating";
  material: "matte" | "glossy" | "soft" | "metal" | "paper";
};
type MaterialParameters = {
  surfaceMix: number;
  darkSurfaceMix: number;
  cushion: number;
  inkTint: number;
  sheen: number;
  textureScale: number;
  lightAngle: number;
};
type Voice = {
  eyebrow: string;
  headline: string;
  body: string;
  primary: string;
  secondary: string;
};
interface LaunchStarter {
  slug: string;
  symbol: string;
  name: string;
  description: string;
  detail: string;
  swatches: readonly [string, string, string];
  voice: Voice;
  foundations: Foundations;
  material: { id: string; parameters: MaterialParameters };
  frame: string;
  character: Omit<ThemeCharacter, "chrome">;
  chrome: Partial<ThemeChrome>;
}

