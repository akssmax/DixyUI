export type OrganicFrame = keyof typeof organicFrameRecipes;
export function isOrganicFrame(frame: string): frame is OrganicFrame {
  return Object.hasOwn(organicFrameRecipes, frame);
}
export const organicStyles = Object.values(organicFrameRecipes).flatMap(
  (recipe) => [...recipe.styles],
);
export function defaultOrganicOrnament(frame: string) {
  const recipe = organicFrameRecipes[isOrganicFrame(frame) ? frame : "forest"];
  return {
    ...recipe.defaults,
    style: recipe.styles[0],
    canopy: canopyShapes[0],
    stem: stemCharacters[0],
  };
}
