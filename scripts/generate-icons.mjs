import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { sizing } from "../packages/tokens/src/sizing.ts";
import { semanticColors } from "../packages/tokens/src/color.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = `/* Generated by scripts/generate-icons.mjs. Do not edit. */
@layer dixy.components {
  ${Object.keys(sizing.icon)
    .map(
      (token) =>
        `.dixy-icon[data-icon-size="${token}"] { --dixy-icon-size: var(--dixy-size-icon-${token}); }`,
    )
    .join("\n")}
  ${Object.keys(semanticColors)
    .filter((role) => role.startsWith("icon."))
    .map(
      (role) =>
        `.dixy-icon[data-icon-color="${role.slice(5)}"] { color: var(--dixy-color-${role.replaceAll(".", "-")}); }`,
    )
    .join("\n")}
}
`;
const target = path.join(root, "packages/react/src/tokens/icon-styles.css");
const content = await format(css, { parser: "css" });
const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== content)
    throw new Error("Icon styles are stale. Run pnpm tokens:generate.");
} else if (current !== content) fs.writeFileSync(target, content);
console.log("Icon styles match existing sizing and semantic color contracts.");
