import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import {
  colorFamilies,
  neutralColorFamilies,
  overlayFamilies,
  toOverlayColor,
  colorSteps,
  colorPalettes,
  colorConstants,
  semanticColors,
  toOklch,
  actionColors,
  focusColor,
  colorReference,
} from "../packages/tokens/src/color.ts";
import { componentColors } from "../packages/react/src/tokens/component-colors.ts";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const header = "/* Generated by scripts/generate-color.mjs. Do not edit. */\n";
const block = (selector, entries) =>
  `${selector} {\n${entries.map(([name, value]) => `--dixy-${name}: ${value};`).join("\n")}\n}\n`;
const roles = (appearance) =>
  Object.entries(semanticColors).map(([name, value]) => [
    `color-${name.replaceAll(".", "-")}`,
    value.light === value.dark
      ? colorReference(value[appearance])
      : `var(--dixy-color-mode-${name.replaceAll(".", "-")})`,
  ]);
const legacy = {
  bg: "background.canvas",
  surface: "background.surface.raised",
  "surface-muted": "background.subtle",
  text: "text.primary",
  "text-muted": "text.secondary",
  border: "border.subtle",
  accent: "background.action.primary",
  "accent-hover": "background.action.primary.hover",
  "accent-soft": "background.action.primary.subtle",
  "accent-text": "text.link",
  "accent-contrast": "text.on.action.primary",
  danger: "text.danger",
  "danger-hover": "background.action.destructive.hover",
  "danger-soft": "background.danger",
  neutral: "background.action.secondary",
  "neutral-hover": "background.action.secondary.hover",
  "neutral-contrast": "text.on.action.secondary",
};
const aliases = Object.entries(legacy).map(([name, role]) => [
  name,
  `var(--dixy-color-${role.replaceAll(".", "-")})`,
]);
const binding = (axis, family) => [
  ...colorSteps.map((step) => [
    `color-${axis}-${step}`,
    `var(--dixy-color-${family}-${step})`,
  ]),
  [`color-${axis}-pressed`, `var(--dixy-color-${family}-pressed)`],
  [`color-${axis}-on-solid`, `var(--dixy-color-${family}-on-solid)`],
  [`color-${axis}-focus`, `var(--dixy-color-${family}-focus)`],
];
const shared = (mode) => [...roles(mode), ...aliases];
const modeCss = ["light", "dark"]
  .map((mode) => {
    const primitives = colorFamilies.flatMap((family) => {
      const action = actionColors(colorPalettes[family][mode], mode);
      return [
        ...colorSteps.map((step) => [
          `color-${family}-${step}`,
          toOklch(colorPalettes[family][mode][step]),
        ]),
        [`color-${family}-pressed`, toOklch(action.pressed)],
        [`color-${family}-on-solid`, toOklch(action.foreground)],
        [
          `color-${family}-focus`,
          toOklch(focusColor(colorPalettes[family][mode], mode)),
        ],
      ];
    });
    return block(
      mode === "light"
        ? ':root, [data-appearance="light"]'
        : '[data-appearance="dark"]',
      [
        ...Object.entries(colorConstants).map(([name, value]) => [
          `color-${name}`,
          toOklch(value),
        ]),
        ...primitives,
        ...Object.entries(semanticColors)
          .filter(([, value]) => value.light !== value.dark)
          .map(([name, value]) => [
            `color-mode-${name.replaceAll(".", "-")}`,
            colorReference(value[mode]),
          ]),
        ...overlayFamilies.flatMap((family) =>
          colorSteps.map((step) => [
            `color-${family}-a${step}`,
            toOverlayColor(family, step),
          ]),
        ),
        ...binding("brand", "blue"),
        ...binding("base", "neutral"),
        ...shared(mode),
      ],
    ).replace("{\n", `{\ncolor-scheme: ${mode};\n`);
  })
  .join("");
// Rebind only roles that depend on a locally changed palette axis.
const axisRules = (axis, attribute, families) =>
  families
    .map((family) =>
      block(`[data-${attribute}="${family}"]`, [
        ...binding(axis, family),
        ...roles("light").filter(([name]) =>
          Object.entries(semanticColors).some(
            ([key, value]) =>
              `color-${key.replaceAll(".", "-")}` === name &&
              (value.light.startsWith(`${axis}.`) ||
                value.dark.startsWith(`${axis}.`)),
          ),
        ),
        ...aliases,
      ]),
    )
    .join("");
const css = `${header}@layer dixy.tokens {\n${modeCss}${axisRules("brand", "accent", colorFamilies)}${axisRules("base", "neutral", neutralColorFamilies)}}\n`;
const componentCss = `${header}@layer dixy.tokens {\n${block(
  ":root, .dixy-theme, [data-appearance], [data-accent], [data-neutral]",
  Object.entries(componentColors).map(([name, role]) => [
    name,
    `var(--dixy-color-${role.replaceAll(".", "-")})`,
  ]),
)}}\n`;
const tailwindName = (name) =>
  name
    .replace(/^background\./, "")
    .replace(/^text\.on\./, "on.")
    .replaceAll(".", "-");
const tailwind = `${header}@import "./color.css";\n@theme inline {\n${Object.keys(
  semanticColors,
)
  .map(
    (name) =>
      `--color-dixy-${tailwindName(name)}: var(--dixy-color-${name.replaceAll(".", "-")});`,
  )
  .join(
    "\n",
  )}\n${colorFamilies.flatMap((family) => colorSteps.map((step) => `--color-dixy-${family}-${step}: var(--dixy-color-${family}-${step});`)).join("\n")}\n${overlayFamilies.flatMap((family) => colorSteps.map((step) => `--color-dixy-${family}-a${step}: var(--dixy-color-${family}-a${step});`)).join("\n")}\n}\n`;
const outputs = {
  "packages/tokens/src/color.css": css,
  "packages/tokens/src/tailwind.css": tailwind,
  "packages/react/src/tokens/component-colors.css": componentCss,
};
if (process.argv.includes("--dist"))
  Object.assign(outputs, {
    "packages/tokens/dist/color.css": css,
    "packages/tokens/dist/tailwind.css": tailwind,
  });
for (const [file, raw] of Object.entries(outputs)) {
  const content = await format(raw, { parser: "css" });
  const target = path.join(root, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (current !== content)
      throw new Error(`${file} is stale. Run pnpm tokens:generate.`);
  } else if (current !== content) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
console.log(
  process.argv.includes("--check")
    ? "Color CSS matches its canonical contracts."
    : "Color palettes, semantics, component aliases and Tailwind bindings generated.",
);
