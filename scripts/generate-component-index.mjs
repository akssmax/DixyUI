// Writes apps/docs/src/generated/component-index.ts: each component's slug,
// title and category, read from the authored registry in apps/docs/src/registry.
//
// The docs shell (sidebar), the landing page and the component route's
// options only need these three fields, but they sit in the site-wide entry
// chunk. Importing the full registry there put every component's controls,
// guidance and lessons (~170 KB) on every page. This index keeps the entry
// small; the full registry loads with the component page that uses it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = path.join(root, "apps/docs/src/registry");
const target = path.join(root, "apps/docs/src/generated/component-index.ts");

const keyText = (name) =>
  ts.isIdentifier(name) || ts.isStringLiteral(name) ? name.text : undefined;

const unwrap = (node) => {
  while (
    node &&
    (ts.isAsExpression(node) ||
      ts.isSatisfiesExpression(node) ||
      ts.isParenthesizedExpression(node))
  )
    node = node.expression;
  return node;
};

/** Exported `const name = { ... }` objects in one registry file. */
function registryObjects(file) {
  const source = ts.createSourceFile(
    file,
    fs.readFileSync(file, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const objects = new Map();
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      const value = unwrap(declaration.initializer);
      if (
        ts.isIdentifier(declaration.name) &&
        value &&
        ts.isObjectLiteralExpression(value)
      )
        objects.set(declaration.name.text, { value, file });
    }
  }
  return objects;
}

function stringField(entry, field, slug, file) {
  const property = entry.properties.find(
    (p) => ts.isPropertyAssignment(p) && keyText(p.name) === field,
  );
  const value = property && unwrap(property.initializer);
  if (
    !value ||
    !(ts.isStringLiteral(value) || ts.isNoSubstitutionTemplateLiteral(value))
  )
    throw new Error(
      `${path.relative(root, file)}: "${slug}" needs a string literal ${field}.`,
    );
  return value.text;
}

export function buildComponentIndex() {
  const objects = new Map();
  for (const name of fs.readdirSync(registryDir).sort())
    if (name.endsWith(".ts"))
      for (const [key, value] of registryObjects(path.join(registryDir, name)))
        objects.set(key, value);
  const registry = objects.get("componentRegistry");
  if (!registry) throw new Error("componentRegistry was not found.");

  // Follow spreads in source order, so keys match Object.keys(componentRegistry).
  const index = new Map();
  const visit = ({ value, file }) => {
    for (const property of value.properties) {
      if (ts.isSpreadAssignment(property)) {
        const spread = ts.isIdentifier(property.expression)
          ? objects.get(property.expression.text)
          : undefined;
        if (!spread)
          throw new Error(
            `${path.relative(root, file)}: cannot resolve spread ${property.expression.getText()}.`,
          );
        visit(spread);
        continue;
      }
      if (!ts.isPropertyAssignment(property)) continue;
      const slug = keyText(property.name);
      const entry = unwrap(property.initializer);
      if (!slug || !ts.isObjectLiteralExpression(entry)) continue;
      index.set(slug, {
        title: stringField(entry, "title", slug, file),
        category: stringField(entry, "category", slug, file),
      });
    }
  };
  visit(registry);

  const lines = [...index].map(
    ([slug, entry]) =>
      `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(entry.title)}, category: ${JSON.stringify(entry.category)} },`,
  );
  return `// Generated by scripts/generate-component-index.mjs from src/registry. Do not edit.
// The light slug/title/category index for the sidebar, landing page and route
// options. The full registry loads only with the component pages.
import type { ComponentSlug } from "../registry/components";

export const componentIndex = {
${lines.join("\n")}
} as const satisfies Record<ComponentSlug, { title: string; category: string }>;

export function isComponentSlug(value: string): value is ComponentSlug {
  return Object.hasOwn(componentIndex, value);
}
`;
}

/** Returns false when --check finds the file stale. */
export function writeComponentIndex({ check = false } = {}) {
  const next = buildComponentIndex();
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current === next) return true;
  if (check) return false;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, next);
  console.log("Generated the docs component index.");
  return true;
}

export const componentRegistryDir = registryDir;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  if (!writeComponentIndex({ check })) {
    console.error("The docs component index is stale. Run pnpm docs:generate.");
    process.exit(1);
  }
}
