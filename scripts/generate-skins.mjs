import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { format } from "prettier";
import { manifests } from "../packages/themes/src/manifests.ts";
import { compileThemeDocument } from "../packages/themes/src/authoring.ts";
import { frameRecipes } from "../packages/themes/src/recipes.ts";
import { themeDocumentSchema } from "../packages/themes/src/theme-schema.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const dist = process.argv.includes("--dist");
const packageRoot = path.join(root, "packages/themes");
const header = "/* Generated by scripts/generate-skins.mjs. Do not edit. */\n";
const write = (relative, text) => {
  const file = path.join(packageRoot, relative);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)
      throw new Error("Stale generated skin: " + relative);
  } else if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
};
const report = [];
for (const m of manifests) {
  const compiled = compileThemeDocument(m.document);
  const definition = compiled.definition;
  const ts = await format(
    '// Generated by scripts/generate-skins.mjs. Do not edit.\nimport type { SkinDefinition } from "@dixy-ui/tokens";\nexport const ' +
      m.symbol +
      " = " +
      JSON.stringify(definition) +
      " as const satisfies SkinDefinition;\nexport const " +
      m.symbol +
      "Theme = " +
      JSON.stringify(compiled.themeProps) +
      " as const;\nexport default " +
      m.symbol +
      ";\n",
    { parser: "typescript" },
  );
  if (!dist) write("src/skins/" + m.slug + ".ts", ts);
  const css = await format(header + compiled.css, { parser: "css" });
  if (gzipSync(css).length > 5120)
    throw new Error("Skin CSS budget exceeded: " + m.slug);
  write((dist ? "dist/" : "generated/") + m.slug + ".css", css);
  report.push({
    id: definition.id,
    cssBytes: Buffer.byteLength(css),
    gzipBytes: gzipSync(css).length,
  });
}
const catalog = manifests.map((m) => ({
  id: "dixy/" + m.slug,
  slug: m.slug,
  symbol: m.symbol,
  name: m.name,
  description: m.description,
  detail: m.detail,
  swatches: m.swatches,
  voice: m.voice,
  appearance: m.document.foundations.appearance,
  bodyFont: m.document.foundations.bodyFont,
  headingFont: m.document.foundations.headingFont,
  border: m.document.foundations.border,
  depth: m.document.foundations.depth,
  defaults: m.document.foundations,
  rendererSymbol: compileThemeDocument(m.document).renderer?.symbol ?? null,
}));
if (!dist)
  write(
    "generated/theme-document.schema.json",
    await format(JSON.stringify(themeDocumentSchema), { parser: "json" }),
  );
if (dist)
  write(
    "dist/theme-document.schema.json",
    await format(JSON.stringify(themeDocumentSchema), { parser: "json" }),
  );
if (!dist)
  write(
    "src/catalog.ts",
    await format(
      "// Generated by scripts/generate-skins.mjs. Do not edit.\nexport const skinCatalog = " +
        JSON.stringify(catalog) +
        ' as const;\nexport type BuiltInSkinId = (typeof skinCatalog)[number]["id"];\n',
      { parser: "typescript" },
    ),
  );
if (!dist) {
  const imports = manifests
    .map((m) => `import { ${m.symbol} } from "@dixy-ui/themes/${m.slug}";`)
    .join("\n");
  const entries = manifests
    .map((m) => `"${m.document.id}": ${m.symbol}`)
    .join(",");
  const renderers = manifests
    .filter((m) => compileThemeDocument(m.document).renderer)
    .map(
      (m) =>
        `"${m.document.id}": lazy(() => import("${compileThemeDocument(m.document).renderer?.entry}"))`,
    )
    .join(",");
  const frames = Object.entries(frameRecipes)
    .filter(([, frame]) => frame.rendererEntry)
    .map(
      ([id, frame]) =>
        `"${id}": lazy(() => import("@dixy-ui/themes/${frame.rendererEntry}"))`,
    )
    .join(",");
  const cssLoaders = manifests
    .map(
      (m) =>
        `"${m.document.id}": () => import("@dixy-ui/themes/${m.slug}.css?inline")`,
    )
    .join(",");
  write(
    "../../apps/docs/src/lib/generated-skin-loaders.ts",
    await format(
      `// Generated by scripts/generate-skins.mjs. Do not edit.
import { lazy } from "react";
import type { ThemeProps } from "@dixy-ui/react";
import type { SkinDefinition } from "@dixy-ui/tokens";
${imports}
export const skinDefinitions: Readonly<Record<string, SkinDefinition>> = {${entries}};
export const ornamentRenderers: Record<string, NonNullable<ThemeProps["ornamentRenderer"]>> = {${renderers}};
export const frameOrnamentRenderers: Record<string, NonNullable<ThemeProps["ornamentRenderer"]>> = {${frames}};
export const skinCSSLoaders: Readonly<Record<string, () => Promise<{ default: string }>>> = {${cssLoaders}};
`,
      { parser: "typescript" },
    ),
  );
}
if (dist) {
  fs.rmSync(path.join(packageRoot, "dist/assets"), {
    recursive: true,
    force: true,
  });
  write("dist/bytes.json", JSON.stringify(report, null, 2) + "\n");
}
console.log(
  (check ? "Verified" : "Generated") +
    ` ${manifests.length} independent 2D skins.`,
);
